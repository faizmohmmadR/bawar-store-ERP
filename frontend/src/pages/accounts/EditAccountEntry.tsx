import { useEffect, useMemo } from 'react';
import { useNavigate, useParams } from 'react-router-dom';
import { useForm } from 'react-hook-form';
import { zodResolver } from '@hookform/resolvers/zod';
import { z } from 'zod';
import { Receipt } from 'lucide-react';
import { Button } from '@/components/ui/button';
import { Form } from '@/components/ui/form';
import { FormActions } from '@/components/forms/FormActions';
import { FormPage } from '@/components/forms/FormPage';
import { useLanguage } from '@/contexts/LanguageContext';
import useFetchObjects from '@/api/useFetchObjects';
import useAdd from '@/api/useAdd';
import useUpdate from '@/api/useUpdate';
import { useRedirectOnSuccess } from '@/hooks/useRedirectOnSuccess';
import AccountEntryForm, {
  accountEntryJournalPayload,
  createAccountEntrySchema,
  defaultAccountEntryValues,
  entryToFormValues,
  singleEntryUpdatePayload,
} from './AccountEntryForm';

const EditAccountEntry = () => {
  const { t } = useLanguage();
  const navigate = useNavigate();
  const { id } = useParams<{ id: string }>();

  const schema = useMemo(() => createAccountEntrySchema(t), [t]);

  const form = useForm<z.infer<typeof schema>>({
    resolver: zodResolver(schema),
    defaultValues: defaultAccountEntryValues(),
  });

  const { data: entry, isLoading: entryLoading } = useFetchObjects({
    queryKey: ['account-entry', id],
    endpoint: `account-entries/${id}`,
    enabled: !!id,
  });

  const { handleUpdate, loading: updateLoading, isSuccess: updateSuccess } = useUpdate({
    queryKey: ['account-entries', 'account-entry'],
    endpoint: 'account-entries',
  });

  const { handleAdd, loading: addLoading, isSuccess: addSuccess } = useAdd({
    queryKey: ['account-entries'],
    endpoint: 'account-entries/journal_entry/',
  });

  useEffect(() => {
    if (entry) {
      form.reset(entryToFormValues(entry));
    }
  }, [entry, form]);

  useRedirectOnSuccess(updateSuccess || addSuccess, '/account-entries');

  const onSubmit = (data: z.infer<typeof schema>) => {
    if (!entry || !id) return;

    const validLines = data.lines.filter(
      (line) => line.account && line.entry_type && (line.debit_amount || line.credit_amount),
    );

    if (validLines.length === 1) {
      handleUpdate(id, singleEntryUpdatePayload(data));
      return;
    }

    handleAdd(accountEntryJournalPayload(data));
  };

  const loading = updateLoading || addLoading;

  if (entryLoading || !entry) {
    return (
      <div className="flex justify-center items-center h-screen">
        <div className="animate-spin rounded-full h-8 w-8 border-b-2 border-primary" />
        <span className="ml-2">{t('common.loading')}</span>
      </div>
    );
  }

  if (entry.content_type) {
    return (
      <FormPage
        title={t('accounts.cannotEditEntry', 'Cannot Edit Entry')}
        description={t('accounts.systemGeneratedEntry', 'This entry was generated by the system and cannot be edited')}
        icon={<Receipt />}
        backTo="/account-entries"
        maxWidth="2xl"
      >
        <div className="space-y-4 text-center">
          <Receipt className="mx-auto h-16 w-16 text-muted-foreground" />
          <div className="space-y-2">
            <h3 className="text-lg font-semibold">
              {t('accounts.systemGeneratedEntryTitle', 'System Generated Entry')}
            </h3>
            <p className="text-muted-foreground">
              {t(
                'accounts.systemGeneratedEntryDesc',
                'This account entry was automatically created by the system and cannot be modified manually.',
              )}
            </p>
          </div>
          <div className="flex justify-center gap-3">
            <Button onClick={() => navigate(`/account-entries/${entry.id}`)}>
              {t('common.viewDetails', 'View Details')}
            </Button>
            <Button variant="outline" onClick={() => navigate('/account-entries')}>
              {t('common.backToList', 'Back to List')}
            </Button>
          </div>
        </div>
      </FormPage>
    );
  }

  return (
    <FormPage
      title={t('accounts.editAccountEntry', 'Edit Account Entry')}
      description={entry.reference_number || `Entry #${entry.id}`}
      icon={<Receipt />}
      backTo="/account-entries"
      maxWidth="6xl"
    >
      <Form {...form}>
        <form onSubmit={form.handleSubmit(onSubmit)} className="space-y-6">
          <AccountEntryForm control={form.control} />
          <FormActions
            onCancel={() => navigate('/account-entries')}
            loading={loading}
            submitLabel={t('accounts.updateEntry', 'Update Entry')}
            loadingLabel={t('common.saving')}
          />
        </form>
      </Form>
    </FormPage>
  );
};

export default EditAccountEntry;
