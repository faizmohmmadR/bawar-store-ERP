def initialize_default_permissions():
    """Create or update all default permissions. Safe to run multiple times."""
    created = 0
    updated = 0

    for perm_data in DEFAULT_PERMISSIONS:
        _, was_created = Permission.objects.update_or_create(
            codename=perm_data['codename'],
            defaults={
                'name': perm_data['name'],
                'module': perm_data['module'],
                'description': perm_data.get('description', ''),
            },
        )
        if was_created:
            created += 1
        else:
            updated += 1

    return {
        'created': created,
        'updated': updated,
        'total': Permission.objects.count(),
    }
